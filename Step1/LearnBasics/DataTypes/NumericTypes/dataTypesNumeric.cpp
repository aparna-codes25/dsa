#include<bits/stdc++.h>
// Includes all cpp libraries
using namespace std;

int main(){

    // int
    int x = 10;
    cout << "Value of x (int) is: " << x << endl;


    // long
    long y = 10000000;
    cout << "Value of y (long) is: " << y << endl;

    // long long
    long long z = 1004048746837456;
    cout << "Value of z (long long) is: " << z << endl;

    // float, double
    float a = 10.5;
    cout << "Value of a (float) is: " << a << endl;
    // float a = 10; also fine
    // internally converts as a = 10.0
    // similarly for double

    double b = 20.99;
    cout << "Value of b (double) is: " << b << endl;

    return 0;
}